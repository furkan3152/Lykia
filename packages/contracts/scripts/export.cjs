#!/usr/bin/env node
// Exports compiled artifacts for the API and the web owner console.
//
// Writes into packages/core/src/contracts/:
//   <Name>.ts   ABI (as const) + creation and runtime bytecode per contract
//   build.ts    package version, source hash and compiler settings
//   index.ts    barrel (also re-exports the hand-written manifest.ts and deployments.ts)
//
// manifest.ts (deploy plan) and deployments.ts (recorded addresses) are hand-written and never
// overwritten. This script never signs or broadcasts anything. Run after `hardhat compile`.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const PKG = path.join(__dirname, "..");
const OUT = path.join(PKG, "..", "core", "src", "contracts");
const version = require(path.join(PKG, "package.json")).version;
const solidity = require(path.join(PKG, "solidity.config.cjs"));

const CONTRACTS = [
  { name: "LykiaAccountFactory", file: "LykiaAccountFactory.sol", deployable: true, environments: ["testnet", "mainnet"] },
  { name: "LykiaRouter", file: "LykiaRouter.sol", deployable: true, environments: ["testnet", "mainnet"] },
  { name: "LykiaAccount", file: "LykiaAccount.sol", deployable: false, environments: [], note: "Deployed by LykiaAccountFactory (implementation + EIP-1167 clones). Use the ABI to talk to accounts." },
  { name: "PracticeVault", file: "practice/PracticeVault.sol", deployable: true, environments: ["testnet"], note: "Arc testnet practice venue." },
  { name: "PracticeSwap", file: "practice/PracticeSwap.sol", deployable: true, environments: ["testnet"], note: "Arc testnet practice venue." },
  { name: "PracticeLending", file: "practice/PracticeLending.sol", deployable: true, environments: ["testnet"], note: "Arc testnet practice venue." },
  { name: "LykiaClQuoter", file: "quoters/LykiaClQuoter.sol", deployable: false, environments: [], note: "Never deployed: the API places the runtime code at a throwaway address through an eth_call state override to quote concentrated-liquidity pools exactly." },
];

function artifact(c) {
  const p = path.join(PKG, "artifacts", "contracts", c.file, `${c.name}.json`);
  if (!fs.existsSync(p)) throw new Error(`missing ${p}; run hardhat compile first`);
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

/** Byte ranges of the runtime code the constructor fills with immutables, from the build info. */
function immutableRanges(c) {
  const dbg = JSON.parse(fs.readFileSync(path.join(PKG, "artifacts", "contracts", c.file, `${c.name}.dbg.json`), "utf8"));
  const info = JSON.parse(fs.readFileSync(path.resolve(path.join(PKG, "artifacts", "contracts", c.file), dbg.buildInfo), "utf8"));
  const out = info.output.contracts[`contracts/${c.file}`][c.name].evm.deployedBytecode.immutableReferences || {};
  return Object.values(out).flat().map((r) => ({ start: r.start, length: r.length })).sort((a, b) => a.start - b.start);
}

function sourceHash() {
  const h = crypto.createHash("sha256");
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name !== "test") walk(full);
      } else if (e.name.endsWith(".sol")) {
        h.update(path.relative(PKG, full));
        h.update(fs.readFileSync(full));
      }
    }
  };
  walk(path.join(PKG, "contracts"));
  return "0x" + h.digest("hex");
}

const compiler = { solc: solidity.version, optimizer: solidity.settings.optimizer, evmVersion: solidity.settings.evmVersion, viaIR: Boolean(solidity.settings.viaIR) };
const srcHash = sourceHash();
const header = (what) =>
  `// GENERATED by packages/contracts/scripts/export.cjs. Do not edit by hand.\n// ${what}\n// @lykia/contracts v${version}, sources ${srcHash}, solc ${compiler.solc}. NOT AUDITED.\n\n`;

fs.mkdirSync(OUT, { recursive: true });
const barrel = [];
for (const c of CONTRACTS) {
  const a = artifact(c);
  const constName = c.name.replace(/^./, (m) => m.toLowerCase()) + "Artifact";
  const body =
    header(`${c.name} ABI and bytecode.`) +
    `export const ${constName} = {\n` +
    `  contractName: ${JSON.stringify(c.name)},\n` +
    `  deployable: ${c.deployable},\n` +
    `  environments: ${JSON.stringify(c.environments)},\n` +
    (c.note ? `  note: ${JSON.stringify(c.note)},\n` : "") +
    `  abi: ${JSON.stringify(a.abi, null, 2).replace(/\n/g, "\n  ")},\n` +
    `  bytecode: ${JSON.stringify(a.bytecode)},\n` +
    `  deployedBytecode: ${JSON.stringify(a.deployedBytecode)},\n` +
    `  immutableReferences: ${JSON.stringify(immutableRanges(c))},\n` +
    `} as const;\n`;
  fs.writeFileSync(path.join(OUT, `${c.name}.ts`), body);
  barrel.push(`export { ${constName} } from "./${c.name}.js";`);
}
fs.writeFileSync(
  path.join(OUT, "build.ts"),
  header("Build information.") + `export const LYKIA_CONTRACTS_BUILD = ${JSON.stringify({ version, sourceHash: srcHash, compiler }, null, 2)} as const;\n`,
);
barrel.push(`export { LYKIA_CONTRACTS_BUILD } from "./build.js";`);
barrel.push(`export * from "./manifest.js";`);
barrel.push(`export * from "./deployments.js";`);
fs.writeFileSync(path.join(OUT, "index.ts"), header("Barrel.") + barrel.join("\n") + "\n");
console.log(`[export] ${CONTRACTS.length} artifacts -> ${path.relative(process.cwd(), OUT)} (v${version}, ${srcHash.slice(0, 12)}…)`);
