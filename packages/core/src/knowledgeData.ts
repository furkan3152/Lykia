/* Load-time check: rows are well formed and every named contract exists in the venue's registry row. */
const KNOWLEDGE_ISSUES = validateKnowledge(KNOWLEDGE_ROWS, {
  contractKeys: (venue) => {
    const row = getProtocol(venue);
    if (!row) return null;
    return [...new Set(Object.values(row.deployments).flatMap((d) => Object.keys(d?.contracts ?? {})))];
  },
});
if (KNOWLEDGE_ISSUES.length > 0) throw new Error(`Invalid knowledge: ${KNOWLEDGE_ISSUES.map((i) => `${i.venue}: ${i.message}`).join("; ")}`);

export function venueKnowledge(venue: string): VenueKnowledge | null {
  return KNOWLEDGE_ROWS.find((row) => row.venue === venue) ?? null;
}
